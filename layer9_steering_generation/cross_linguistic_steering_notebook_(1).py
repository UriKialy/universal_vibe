def get_formality_scores_batch(texts, batch_size=10, max_retries=3):
    """
    Use GPT-4o to rate formality for multiple texts at once.
    Returns a list of scores (0-1) corresponding to input texts.
    """
    all_scores = []

    for i in range(0, len(texts), batch_size):
        batch = texts[i:i+batch_size]
        batch_scores = _process_batch(batch, max_retries)
        all_scores.extend(batch_scores)

        # Small delay to avoid rate limits
        if i + batch_size < len(texts):
            time.sleep(0.5)

    return all_scores

def _process_batch(texts, max_retries=3):
    """Process a single batch of texts."""
    # Filter out empty texts, keep track of indices
    valid_indices = []
    valid_texts = []
    results = [None] * len(texts)  # Default scores

    for idx, text in enumerate(texts):
        if text and len(str(text).strip()) >= 3:
            valid_indices.append(idx)
            valid_texts.append(str(text)[:300])  # Truncate to save tokens

    if not valid_texts:
        return results

    # Build batch prompt - simpler format, no markers
    texts_formatted = "\n".join([f"{i+1}. \"{t}\"" for i, t in enumerate(valid_texts)])

    prompt = f"""Rate the formality of each text below on a scale from 0 to 1.
- 0 = very informal, casual, slang, colloquial
- 1 = very formal, professional, academic

Return ONLY a JSON array of numbers, nothing else. Example: [0.2, 0.8, 0.5]
respond in the following structure: [CLASSIFICATION_START]your score[CLASSIFICATION_END]

Texts:
{texts_formatted}"""

    for attempt in range(max_retries):
        try:
            response = client.chat.completions.create(
                model="gpt-4o-mini",  # Using mini for cost savings
                messages=[
                    {"role": "system", "content": "You are a formality scorer. Return only a JSON array of numbers between 0 and 1."},
                    {"role": "user", "content": prompt}
                ],
                max_tokens=10 * len(valid_texts),
                temperature=0
            )
            response_text = response.choices[0].message.content.strip()

            # Extract JSON array - handle markdown code blocks
            response_text = response_text.replace('```json', '').replace('```', '').strip()

            # Find array in response
            match = re.search(r'\[[\d\.,\s]+\]', response_text)
            if match:
                import json
                scores = json.loads(match.group())

                # Map back to original indices
                for idx, score in zip(valid_indices, scores):
                    if idx < len(results):
                        results[idx] = min(max(0, float(score)), 1)
                return results
            else:
                raise ValueError(f"No JSON array found in: {response_text}")

        except Exception as e:
            if attempt == max_retries - 1:
                print(f"Warning: Batch failed: {e}")
            else:
                time.sleep(1)  # Wait before retry

    return results

def get_formality_score_gpt4o(text, max_retries=3):
    """Single text scoring (for compatibility). Use batch version when possible."""
    return get_formality_scores_batch([text], batch_size=1, max_retries=max_retries)[0]

