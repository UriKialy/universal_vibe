import re

def detect_language(text):
    """
    Detect if text is primarily in English, Hebrew, Russian, or other.
    Returns: 'english', 'hebrew', 'russian', or 'other'
    """
    if pd.isna(text) or not text or len(str(text).strip()) == 0:
              return 'other'

    # Count character types
    hebrew_chars = len(re.findall(r'[\u0590-\u05FF]', text))
    russian_chars = len(re.findall(r'[\u0400-\u04FF]', text))
    latin_chars = len(re.findall(r'[a-zA-Z]', text))

    # Other scripts (Hindi, Arabic, Chinese, etc.)
    devanagari_chars = len(re.findall(r'[\u0900-\u097F]', text))  # Hindi
    arabic_chars = len(re.findall(r'[\u0600-\u06FF]', text))
    chinese_chars = len(re.findall(r'[\u4E00-\u9FFF]', text))
    japanese_chars = len(re.findall(r'[\u3040-\u309F\u30A0-\u30FF]', text))
    korean_chars = len(re.findall(r'[\uAC00-\uD7AF]', text))
    thai_chars = len(re.findall(r'[\u0E00-\u0E7F]', text))

    other_script_chars = devanagari_chars + arabic_chars + chinese_chars + japanese_chars + korean_chars + thai_chars

    total_alpha = hebrew_chars + russian_chars + latin_chars + other_script_chars

    if total_alpha == 0:
        return 'other'

    # If significant other script presence, mark as other
    if other_script_chars / total_alpha > 0.3:
        return 'other'

    # Determine primary language
    if hebrew_chars / total_alpha > 0.4:
        return 'hebrew'
    elif russian_chars / total_alpha > 0.4:
        return 'russian'
    elif latin_chars / total_alpha > 0.4:
        return 'latin'
    else:
        return 'other'
